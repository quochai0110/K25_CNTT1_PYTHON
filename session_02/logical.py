#  TOÁN TỬ LOGIC: AND, OR, NOT
#  AND: TOÁN TỬ KẾT HỢP: tất cả điều kiện đúng thì mới đúng
result = True and True and False
print("kết quả: ", result)
#  OR: TOÁN TỬ HOẶC: trong các mệnh đề chỉ cần 1 mệnh đề TRUE thì kết 
# quả sẽ TRUE
result = True or False
print("Kết quả OR: ", result)
#  NOT: TOÁN TỬ PHỦ ĐỊNH
result = not True
print ("kết quả toán tử not: ", result)